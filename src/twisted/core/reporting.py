def render_executive_html(data: ReportData) -> str:
    """Render a single-page executive summary in print-ready HTML.

    Designed to fit on one A4 page when run through WeasyPrint."""
    from jinja2 import Environment

    counts = data.severity_counts()
    severity_notes = {
        "Critical": "Block exploitation path; remediate < 48 h.",
        "High": "Active risk; remediate within sprint.",
        "Medium": "Schedule remediation in next backlog grooming.",
        "Low": "Address during ordinary maintenance.",
        "Informational": "Operational hygiene; defensible posture.",
    }
    severity_order = ("Critical", "High", "Medium", "Low", "Informational")
    by_sev = data.by_severity()
    top: list[FindingSummary] = []
    for sev in severity_order:
        for f in by_sev.get(sev, []):
            top.append(f)
            if len(top) >= 5:
                break
        if len(top) >= 5:
            break
    env = Environment(autoescape=True)
    tpl = env.from_string(_EXEC_TEMPLATE)
    return tpl.render(
        data=data, counts=counts, severity_notes=severity_notes,
        top_findings=top, has_any=bool(data.findings),
        started=data.engagement_started.date().isoformat()
                 if data.engagement_started else "TBD",
        ended=data.engagement_ended.date().isoformat()
                 if data.engagement_ended else "TBD",
        now=datetime.now().isoformat(timespec="seconds"),
    )


# ──────────────────────────── Builder helpers ────────────────────────────


def finding_summary_from_orm(f: Any) -> FindingSummary:
    """Build a FindingSummary from a Finding ORM instance.

    Kept loose-typed so this module does not import from .models in a way that
    creates a circular dep with reporting being a primitive.
    """
    return FindingSummary(
        id=getattr(f, "id", None),
        title=f.title,
        severity=str(f.severity).split(".")[-1].lower() if f.severity else "info",
        cvss_score=f.cvss_score,
        cvss_vector=f.cvss_vector,
        cwe=f.cwe,
        affected_component=f.affected_component,
        description=f.description,
        root_cause=f.root_cause,
        repro_steps=f.repro_steps,
        impact=f.impact,
        remediation=f.remediation,
        references=list(f.references or []),
        evidence_paths=[e.redacted_path or e.path for e in (getattr(f, "evidence", []) or [])],
    )


def auto_severity(score: float | None) -> str:
    return severity_for_score(score) if score is not None else "Informational"
